def _bound_tex(b):
    """Render a bound string as maths: '<= 2.79 (studentised)' -> '$\\le 2.79$ (studentised)'."""
    b = b.strip()
    m = re.match(r"^<=\s*([\d.]+)(.*)$", b)
    if m:
        return rf"$\le {m.group(1)}$" + esc(m.group(2))
    m = re.match(r"^in \[([-\d.]+),\s*([-\d.]+)\]$", b)
    if m:
        return rf"$\in [{m.group(1)}, {m.group(2)}]$"
    m = re.match(r"^\(<=\s*([\d.]+),\s*(.*)\)$", b)
    if m:
        return rf"($\le {m.group(1)}$, " + esc(m.group(2)) + ")"
    return esc(b)


def gate_rows(g):
    order = ["G1-tail", "G1-mean", "G2a", "G2b", "G2b-old"] + [f"G3:{k}" for k in EXO] + ["G4a", "G4b", "G4c"]
    desc = {"G1-tail": "vanilla column means", "G1-mean": "martingale column means",
            "G2a": "martingale column sds",
            "G2b": "vanilla column sds, studentised",
            "G2b-old": r"\emph{superseded: flat sd-ratio bound}",
            "G4a": "realised-variance dispersion", "G4b": "volatility clustering",
            "G4c": "leverage correlation"}
    for k in EXO:
        desc[f"G3:{k}"] = EXO_TEX[k]
    out = []
    for k in order:
        if k not in g:
            continue
        v = g[k]
        mark = r"\checkmark" if v["passed"] else r"$\times$"
        if k == "G2b-old":
            mark = r"\emph{not gated}"
        out.append([esc(k), desc.get(k, ""), num(v["value"]), _bound_tex(v["bound"]), mark])
    return out


