def load(*path, required=True):
    p = os.path.join(REPO, *path)
    if not os.path.exists(p):
        if required:
            raise FileNotFoundError(p)
        return None
    with open(p) as f:
        return json.load(f)


def esc(s):
    return str(s).replace("_", r"\_").replace("%", r"\%")


def num(x, d=4):
    return "---" if x is None else f"{x:.{d}f}"


def write(name, body, caption, label, note=None, star=False, source=""):
    os.makedirs(TAB, exist_ok=True)
    env = "table*" if star else "table"
    out = [f"% generated by paper/build_tables.py on {date.today()} -- do not edit by hand",
           f"% source: {source}",
           f"\\begin{{{env}}}[t]", r"\centering", r"\small", body.rstrip()]
    if note:
        out.append(r"\par\smallskip{\footnotesize " + note + "}")
    out += [f"\\caption{{{caption}}}", f"\\label{{{label}}}", f"\\end{{{env}}}", ""]
    p = os.path.join(TAB, name)
    with open(p, "w") as f:
        f.write("\n".join(out))
    print(f"  wrote tables/{name}")


def write_figure(stem, caption, label, star=False, height="4.3cm"):
    """Float wrapper for a generated figure, matching the table floats.

    The height cap is the page budget and must not be relaxed. `width=\\textwidth`
    is given alongside it so graphicx scales to whichever binds first: the height
    never exceeds the cap, and the figure never overruns the column.
    """
    os.makedirs(FIG, exist_ok=True)
    env = "figure*" if star else "figure"
    out = [f"% generated by paper/build_tables.py on {date.today()} -- do not edit by hand",
           f"% height cap {height} is the page budget (see paper/OVERLEAF.md)",
           f"\\begin{{{env}}}[t]", r"\centering",
           f"  \\includegraphics[width=\\textwidth,height={height},keepaspectratio]{{figures/{stem}}}",
           f"  \\caption{{{caption}}}", f"  \\label{{{label}}}", f"\\end{{{env}}}", ""]
    with open(os.path.join(FIG, stem + ".tex"), "w") as f:
        f.write("\n".join(out))
    print(f"  wrote figures/{stem}.tex")


def tabular(cols, header, rows, rules=()):
    L = [f"\\begin{{tabular}}{{{cols}}}", r"\toprule", " & ".join(header) + r" \\", r"\midrule"]
    for i, r in enumerate(rows):
        L.append(" & ".join(r) + r" \\")
        if i + 1 in rules:
            L.append(r"\midrule")
    L += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(L)


